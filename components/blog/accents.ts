// Акцентные палитры для статей блога (разный дизайн на статью).
// Применяются как CSS-переменные --a-50..--a-700 на корне статьи,
// блоки используют bg-[var(--a-500)] и т.п.
import type { CSSProperties } from "react";

type Shades = Record<"50" | "100" | "200" | "300" | "400" | "500" | "600" | "700", string>;

export const ACCENTS: Record<string, Shades> = {
  teal:    { "50": "#e6f7f5", "100": "#b3e8e2", "200": "#80d9cf", "300": "#4dcabc", "400": "#26bfa9", "500": "#00a896", "600": "#009787", "700": "#008575" },
  indigo:  { "50": "#eef2ff", "100": "#e0e7ff", "200": "#c7d2fe", "300": "#a5b4fc", "400": "#818cf8", "500": "#6366f1", "600": "#4f46e5", "700": "#4338ca" },
  amber:   { "50": "#fffbeb", "100": "#fef3c7", "200": "#fde68a", "300": "#fcd34d", "400": "#fbbf24", "500": "#f59e0b", "600": "#d97706", "700": "#b45309" },
  emerald: { "50": "#ecfdf5", "100": "#d1fae5", "200": "#a7f3d0", "300": "#6ee7b7", "400": "#34d399", "500": "#10b981", "600": "#059669", "700": "#047857" },
  violet:  { "50": "#f5f3ff", "100": "#ede9fe", "200": "#ddd6fe", "300": "#c4b5fd", "400": "#a78bfa", "500": "#8b5cf6", "600": "#7c3aed", "700": "#6d28d9" },
  rose:    { "50": "#fff1f2", "100": "#ffe4e6", "200": "#fecdd3", "300": "#fda4af", "400": "#fb7185", "500": "#f43f5e", "600": "#e11d48", "700": "#be123c" },
  sky:     { "50": "#f0f9ff", "100": "#e0f2fe", "200": "#bae6fd", "300": "#7dd3fc", "400": "#38bdf8", "500": "#0ea5e9", "600": "#0284c7", "700": "#0369a1" },
};

export const ACCENT_NAMES = Object.keys(ACCENTS);

export function accentVars(name?: string): CSSProperties {
  const a = (name && ACCENTS[name]) || ACCENTS.teal;
  return {
    "--a-50": a["50"], "--a-100": a["100"], "--a-200": a["200"], "--a-300": a["300"],
    "--a-400": a["400"], "--a-500": a["500"], "--a-600": a["600"], "--a-700": a["700"],
  } as CSSProperties;
}
